
import { GoogleGenAI } from "@google/genai";
import { Pose } from "./types";

export const transformImage = async (userImageBase64: string, selectedPose: Pose): Promise<string> => {
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });
  
  // Clean up base64 prefix if exists
  const imageData = userImageBase64.replace(/^data:image\/\w+;base64,/, "");

  const prompt = `
    TASK: Transform the person in the provided image into the following yoga/fitness pose: "${selectedPose.name}".
    POSE DESCRIPTION: ${selectedPose.description}.
    
    INSTRUCTIONS:
    - Keep the subject's identity, clothing, and environment consistent.
    - Adjust only the body posture and limb placement to match the "${selectedPose.name}" exactly.
    - The final output must be a high-quality photorealistic image of the same person performing this pose.
    - Preserve lighting and background details from the original photo.
  `;

  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash-image',
      contents: {
        parts: [
          {
            inlineData: {
              data: imageData,
              mimeType: 'image/jpeg',
            },
          },
          {
            text: prompt,
          },
        ],
      },
    });

    for (const part of response.candidates[0].content.parts) {
      if (part.inlineData) {
        return `data:image/png;base64,${part.inlineData.data}`;
      }
    }

    throw new Error("No image was generated by the model.");
  } catch (error) {
    console.error("Gemini transformation error:", error);
    throw error;
  }
};
